"""Synthetic SEC-MS dataset for the testcell (run once; outputs are committed). Known truth, so the toolkit can be tested.

Column law: log10(MW kDa) = 3.6 - 0.055 x fraction, 50 fractions (fraction 1 ~ 3.5 MDa, 50 ~ 8 kDa), void <= 4.
Each protein elutes as Gaussians (sigma 1.2 fractions) at its states' masses with weights = state fractions:
  complexes of complexes.tsv (Complex Portal ids)  -> complex mass (sum of subunit masses x stoich), weight ALPHA
  homo-oligomers of complexes.tsv (<GENE>_x<n>)    -> n x monomer, weight ALPHA
  20S proteasome subunits (PSMA*, PSMB*)           -> 26S 0.30, 20S (750 kDa) 0.55, free 0.15 (apex at 20S, as the
                                                     human anchors PSMA1 / PSMB5 assume)
  native-mass anchors (toolkits/secms/data/anchors_native_mass_human.tsv) present in the testcell -> anchor mass
  everything else                                  -> monomer
Peptides: 4 per protein, response factors lognormal(0, 0.5), 10% multiplicative noise per replicate (2 replicates),
q-values 0.001; noise rows that the toolkit must drop: q-value 0.05 rows (large intensity in the void), a shared peptide
("P1/P2") and a decoy protein. Outputs (tests/data/testcell/):
  secms_peptides.tsv        protein, peptide, fraction, intensity, replicate, qvalue          (format peptide_long)
  secms_annotation.tsv      uniprot, gene, mass_da, tm                                        (toolkit annotation)
  secms_complexportal.tsv   Complex Portal ComplexTab columns used by the toolkit (taxon 9606)
  secms_humap.csv           hu.MAP-like membership (HuMAP3_ID, Uniprot_ACCs)
  secms_pair_candidates.tsv uniprot_a, uniprot_b
  secms_standards.tsv       fraction, kda, name (column standards on the column law)
  secms_truth.tsv           gene, uniprot, mono_kda, state_kda, min_ratio, assembled_true (fraction in multimeric states)

    PYTHONHASHSEED=0 python tests/data/testcell/make_testcell_secms.py
"""
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
NF, A0, B0, SIG, VOID = 50, 3.6, 0.055, 1.2, 4
ALPHA = {"CPX-5993": 0.85, "CPX-6030": 0.75, "CPX-3288": 0.4, "CPX-2940": 0.6, "CPX-6151": 0.9, "GAPDH_x4": 0.95,
         "ALDOA_x4": 0.9, "ENO1_x2": 0.9, "YWHAZ_afx2": 0.9, "HSPD1_x7": 0.8, "CS_x2": 0.85, "HSP90B1_afx2": 0.7}
HDR = ("# synthetic testcell SEC-MS (generated by tests/data/testcell/make_testcell_secms.py; column law log10 kDa = 3.6 - "
       "0.055 x fraction, 50 fractions, 2 replicates; truth in secms_truth.tsv)\n")


def frac_of(kda):
    return (A0 - np.log10(kda)) / B0


def main():
    rng = np.random.default_rng(20261116)
    read = lambda f: pd.read_csv(os.path.join(HERE, f), sep="\t", comment="#")
    prot, loc, cpx = read("proteome.tsv"), read("localisation.tsv"), read("complexes.tsv")
    mono = dict(zip(prot.gene, prot.mass_da / 1e3)); acc = dict(zip(prot.gene, prot.uniprot)); copies = dict(zip(prot.gene, prot.copies))
    anchors = pd.read_csv(os.path.join(ROOT, "toolkits", "secms", "data", "anchors_native_mass_human.tsv"), sep="\t", comment="#")
    states = {g: [] for g in prot.gene}                            # gene -> [(kDa, weight)]
    for r in cpx.itertuples(index=False):
        sub = {t.split(":")[0]: int(t.split(":")[1]) for t in r.subunits.split(";")}
        mw = sum(mono[g] * s for g, s in sub.items())
        for g in sub:
            if g.startswith(("PSMA", "PSMB")) and r.complex_id == "CPX-5993":
                states[g] += [(mw, 0.30), (750.0, 0.55)]
            else:
                states[g].append((mw, ALPHA[r.complex_id]))
    for r in anchors.itertuples(index=False):
        if r.gene in states and not states[r.gene] and r.native_kda > 1.5 * mono[r.gene]:
            states[r.gene].append((float(r.native_kda), 0.8))
    rows, truth = [], []
    x = np.arange(1, NF + 1)
    for g in prot.gene:
        st = states[g]
        wa = sum(w for _, w in st)
        prof = (1 - wa) * np.exp(-0.5 * ((x - frac_of(mono[g])) / SIG) ** 2)
        for kda, w in st:
            prof = prof + w * np.exp(-0.5 * ((x - frac_of(kda)) / SIG) ** 2)
        prof = prof / prof.sum() * copies[g] * 10.0
        truth.append(dict(gene=g, uniprot=acc[g], mono_kda=mono[g], state_kda=";".join(f"{k:.0f}" for k, _ in st),
                          min_ratio=min([k / mono[g] for k, _ in st], default=np.nan),
                          assembled_true=round(sum(w for k, w in st if k >= 1.5 * mono[g]), 4)))
        rf = rng.lognormal(0, 0.5, 4)
        for rep in (1, 2):
            noise = 1 + 0.1 * rng.standard_normal((4, NF))
            I = np.clip(rf[:, None] * prof[None, :] * noise, 0, None)
            for j in range(4):
                for f in range(NF):
                    if I[j, f] > 1e-3 * I[j].max():
                        rows.append(dict(protein=acc[g], peptide=f"{g}_PEP{j + 1}", fraction=f + 1, intensity=round(float(I[j, f]), 2),
                                         replicate=rep, qvalue=0.001))
            rows.append(dict(protein=acc[g], peptide=f"{g}_BADQ", fraction=2, intensity=float(copies[g] * 100), replicate=rep,
                             qvalue=0.05))                      # must be filtered (q-value)
    for rep in (1, 2):
        rows.append(dict(protein="P99999/Q99999", peptide="SHARED", fraction=30, intensity=1e9, replicate=rep, qvalue=0.001))
        rows.append(dict(protein="DECOY_P12345", peptide="DECOY", fraction=30, intensity=1e9, replicate=rep, qvalue=0.001))
    w = lambda df, f, sep="\t": (open(os.path.join(HERE, f), "w").write(HDR if sep == "\t" else ""),
                                 df.to_csv(os.path.join(HERE, f), sep=sep, index=False, mode="a"))
    w(pd.DataFrame(rows), "secms_peptides.tsv")
    ann = pd.DataFrame(dict(uniprot=prot.uniprot, gene=prot.gene, mass_da=prot.mass_da,
                            tm=prot.gene.map(dict(zip(loc.gene, loc.transmembrane))).fillna(False).astype(bool)))
    w(ann, "secms_annotation.tsv")
    cp = []
    for r in cpx.itertuples(index=False):
        if not r.complex_id.startswith("CPX-"):
            continue
        sub = {t.split(":")[0]: int(t.split(":")[1]) for t in r.subunits.split(";")}
        cp.append({"#Complex ac": r.complex_id, "Recommended name": f"testcell complex {r.complex_id}", "Taxonomy identifier": 9606,
                   "Expanded participant list": "|".join(f"{acc[g]}({s})" for g, s in sub.items())})
    cp.append({"#Complex ac": "CPX-TEST20S", "Recommended name": "testcell 20S proteasome", "Taxonomy identifier": 9606,
               "Expanded participant list": "|".join(f"{acc[g]}(2)" for g in prot.gene if g.startswith(("PSMA", "PSMB")))})
    pd.DataFrame(cp).to_csv(os.path.join(HERE, "secms_complexportal.tsv"), sep="\t", index=False)
    pd.DataFrame([dict(HuMAP3_ID="HuMAP3_TEST1", ComplexConfidence=1, Uniprot_ACCs=f"{acc['HSP90AA1']} {acc['CDC37']}")]) \
        .to_csv(os.path.join(HERE, "secms_humap.csv"), index=False)
    pairs = [("HSP90AA1", "CDC37"), ("TCP1", "CCT2"), ("GAPDH", "PGK1"), ("PFN1", "ACTB")]
    w(pd.DataFrame(dict(uniprot_a=[acc[a] for a, _ in pairs], uniprot_b=[acc[b] for _, b in pairs])), "secms_pair_candidates.tsv")
    std = pd.DataFrame(dict(name=["thyroglobulin", "ferritin", "aldolase", "conalbumin", "ovalbumin", "ribonuclease A"],
                            kda=[669.0, 440.0, 158.0, 75.0, 44.0, 13.7]))
    std["fraction"] = frac_of(std.kda).round(2)
    w(std[["fraction", "kda", "name"]], "secms_standards.tsv")
    w(pd.DataFrame(truth), "secms_truth.tsv")
    print(f"{len(rows)} peptide rows, {len(cp)} complexes, {len(truth)} proteins")


if __name__ == "__main__":
    main()
